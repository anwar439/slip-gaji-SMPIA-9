function generateSalaryRecord(
  emp: Employee,
  period: string,
  periodLabel: string,
  paymentDate: string,
  overtime: number = 0,
  bonus: number = 0,
  thr: number = 0,
  kasbon: number = 0,
  lateHours: number = 0,
  isPublished: boolean = true
): SalaryRecord {
  // Compute default period start and end dates based on YYYY-MM
  const [yearStr, monthStr] = period.split('-');
  const year = parseInt(yearStr, 10) || 2025;
  const month = parseInt(monthStr, 10) || 1;
  const lastDay = new Date(year, month, 0).getDate();
  const periodStartDate = `${period}-01`;
  const periodEndDate = `${period}-${String(lastDay).padStart(2, '0')}`;

  // Allowances based on status/subject
  const positionAllowance = emp.subject?.includes('Kepala') || emp.level?.includes('VI')
    ? 2000000
    : emp.level?.includes('V D')
    ? 1500000
    : emp.category?.includes('GURU')
    ? 1000000
    : 500000;

  const transportAllowance = 800000;
  const mealAllowance = 1000000;
  const attendanceAllowance = lateHours > 0 ? 300000 : 500000;
  const dailySalaryRate = 0;
  const dailySalaryDays = 0;
  const dailySalaryTotal = 0;
  const otherEarnings = 0;

  const totalEarnings =
    emp.baseSalary +
    dailySalaryTotal +
    positionAllowance +
    transportAllowance +
    mealAllowance +
    attendanceAllowance +
    overtime +
    bonus +
    thr +
    otherEarnings;

  // Deductions
  const bpjsKetenagakerjaan = Math.round(emp.baseSalary * 0.03);
  const bpjsKesehatan = Math.round(emp.baseSalary * 0.01);
  const pph21 = Math.round(emp.baseSalary * 0.04);
  const latePenalty = lateHours * 50000;
  const absencePenalty = 0;
  const loanDeduction = kasbon;
  const coopDeduction = 100000;
  const otherDeductions = 0;

  const totalDeductions =
    bpjsKetenagakerjaan +
    bpjsKesehatan +
    pph21 +
    latePenalty +
    absencePenalty +
    loanDeduction +
    coopDeduction +
    otherDeductions;

  const netSalary = totalEarnings - totalDeductions;

  const periodCode = period.replace('-', '');
  const cleanNip = (emp.nip && emp.nip !== '-') ? emp.nip : `ID-${emp.no || 1}`;
  const slipNumber = `SLIP/${periodCode}/${cleanNip}`;

  return {
    id: `rec-${emp.id}-${period}`,
    slipNumber,
    employeeId: emp.id,
    employeeNip: (emp.nip && emp.nip !== '-') ? emp.nip : (emp.nik && emp.nik !== '-' ? emp.nik : `EMP-${emp.no}`),
    employeeName: emp.name,
    employeePosition: emp.subject || emp.position,
    employeeDepartment: emp.category || emp.department,
    period,
    periodLabel,
    periodStartDate,
    periodEndDate,
    paymentDate,
    status: isPublished ? 'published' : 'draft',
    attendance: {
      workDays: 22,
      presentDays: 22 - (lateHours > 2 ? 1 : 0),
      sickDays: 0,
      permissionDays: 0,
      paidLeaveDays: 0,
      absentDays: 0,
      lateHours,
    },
    basicSalary: emp.baseSalary,
    dailySalaryRate,
    dailySalaryDays,
    dailySalaryTotal,
    positionAllowance,
    transportAllowance,
    mealAllowance,
    attendanceAllowance,
    overtimePay: overtime,
    bonusPay: bonus,
    thrPay: thr,
    otherEarnings,
    otherEarningsNote: '',
    totalEarnings,

    bpjsKetenagakerjaan,
    bpjsKesehatan,
    pph21,
    latePenalty,
    absencePenalty,
    loanDeduction,
    coopDeduction,
    otherDeductions,
    otherDeductionsNote: '',
    totalDeductions,

    netSalary,
    notes: 'Slip gaji resmi SMP Islam Al Azhar 9 periode ini telah diverifikasi.',
    publishedAt: isPublished ? `${paymentDate} 09:00:00` : undefined,
    uploadedAt: `${paymentDate} 08:30:00`,
  };
}

