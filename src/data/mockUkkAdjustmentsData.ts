import { UkkAdjustmentRecord } from '../types';

export function calculateUkkAdjustmentRow(
  row: Partial<UkkAdjustmentRecord>
): UkkAdjustmentRecord {
  const ukkTransportMakan = Number(row.ukkTransportMakan) || 0;
  const tunjanganWaliKelas = Number(row.tunjanganWaliKelas) || 0;
  const tunjanganStaffPimpinan = Number(row.tunjanganStaffPimpinan) || 0;
  const tunjanganLain = Number(row.tunjanganLain) || 0;

  // JUMLAH (Subtotal Penambahan)
  const totalPenambahan = ukkTransportMakan + tunjanganWaliKelas + tunjanganStaffPimpinan + tunjanganLain;

  // POTONGAN
  const potonganKesra = Number(row.potonganKesra) || 0;
  const potonganKoperasiYpi = Number(row.potonganKoperasiYpi) || 0;
  const potonganKoperasiYwam = Number(row.potonganKoperasiYwam) || 0;
  const potonganYwAmjp = Number(row.potonganYwAmjp) || 0;
  const potonganLain = Number(row.potonganLain) || 0;

  const totalPotongan = potonganKesra + potonganKoperasiYpi + potonganKoperasiYwam + potonganYwAmjp + potonganLain;

  // JUMLAH DITERIMA (UKK Bersih Akhir)
  const jumlahDiterima = Math.max(0, totalPenambahan - totalPotongan);

  return {
    id: row.id || `ukk-adj-${Date.now()}-${Math.random().toString(36).substr(2, 6)}`,
    no: Number(row.no) || 1,
    nip: (row.nip || '').trim(),
    bankAccountNumber: (row.bankAccountNumber || '').trim(),
    bankName: row.bankName || 'BSI',
    name: (row.name || '').trim(),
    ukkTransportMakan,
    tunjanganWaliKelas,
    tunjanganStaffPimpinan,
    tunjanganLain,
    totalPenambahan,
    potonganKesra,
    potonganKoperasiYpi,
    potonganKoperasiYwam,
    potonganYwAmjp,
    potonganLain,
    totalPotongan,
    jumlahDiterima,
    period: row.period || '2026-08',
    periodLabel: row.periodLabel || 'Agustus 2026',
    notes: row.notes || '',
    lastUpdated: row.lastUpdated || new Date().toISOString(),
  };
}

