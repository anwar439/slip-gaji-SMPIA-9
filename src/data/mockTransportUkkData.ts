import { TransportUkkRecord } from '../types';

export function calculateTransportUkkRow(
  row: Partial<TransportUkkRecord>,
  options?: { recalculateKotor?: boolean; recalculatePotongan?: boolean }
): TransportUkkRecord {
  const hariKerja = Number(row.hariKerja) || 0;
  const sakit = Number(row.sakit) || 0;
  const izin = Number(row.izin) || 0;
  const alpa = Number(row.alpa) || 0;
  const cuti = Number(row.cuti) || 0;
  const dinluar = Number(row.dinluar) || 0;
  const jumlahTidakMasuk = sakit + izin + alpa + cuti + dinluar;
  const jumlahHadir = row.jumlahHadir !== undefined && row.jumlahHadir !== null
    ? Number(row.jumlahHadir)
    : Math.max(0, hariKerja - jumlahTidakMasuk);

  // Keterlambatan & Pulang Cepat
  // Aturan Yayasan / Sekolah:
  // - Terlambat < 5 Menit: Potongan 50% UKK hari itu (0.5 x tarif UKK harian)
  // - Terlambat > 5 Menit: Potongan 100% UKK hari itu (1.0 x tarif UKK harian / UKK hari itu hilang 100%)
  // - Pulang Cepat < 5 Menit: Potongan 50% UKK hari itu (0.5 x tarif UKK harian)
  // - Pulang Cepat > 5 Menit: Potongan 100% UKK hari itu (1.0 x tarif UKK harian / UKK hari itu hilang 100%)
  const datangLambatMin5 = Number(row.datangLambatMin5) || 0;
  const datangLambatPlus5 = Number(row.datangLambatPlus5) || 0;
  const pulangCepatMin5 = Number(row.pulangCepatMin5) || 0;
  const pulangCepatPlus5 = Number(row.pulangCepatPlus5) || 0;
  const terlambatMenit = Number(row.terlambatMenit) || (datangLambatMin5 * 3 + datangLambatPlus5 * 10 + pulangCepatMin5 * 3 + pulangCepatPlus5 * 10);
  const kondite = Number(row.kondite) || 0;
  const subuhOnline = Number(row.subuhOnline) || 0;

  // Nilai UKK per hari (misal 132.250 untuk guru, 158.250 / 147.750 untuk pimpinan, 66.125 untuk CPG)
  let ukkPerhari = Number(row.ukkPerhari) || 0;
  const ukkKinerjaPersen = Number(row.ukkKinerjaPersen) || 0;

  // Base UKK Bruto (Nilai acuan untuk kehadiran penuh pada hari kerja)
  let baseUkkBruto = Number(row.baseUkkBruto);
  if (!baseUkkBruto || isNaN(baseUkkBruto) || baseUkkBruto <= 0) {
    const existingKotor = Number(row.ukkKotor ?? row.ukkBruto);
    if (!isNaN(existingKotor) && existingKotor > 0) {
      // Jika existing data hadir kurang dari hari kerja, prorata ke full hari kerja untuk mendapatkan base
      if (hariKerja > 0 && jumlahHadir > 0 && jumlahHadir < hariKerja) {
        baseUkkBruto = Math.round((existingKotor / jumlahHadir) * hariKerja);
      } else {
        baseUkkBruto = existingKotor;
      }
    } else if (ukkPerhari > 0) {
      const baseDays = hariKerja > 0 ? hariKerja * 1.15 : 26;
      baseUkkBruto = Math.round(ukkPerhari * baseDays * ((ukkKinerjaPersen || 100) / 100));
    } else {
      baseUkkBruto = 3484270;
    }
  }

  // Jika ukkPerhari belum terdefinisi namun UKK kotor ada, turunkan tarif per harinya secara presisi
  if (ukkPerhari === 0 && baseUkkBruto > 0) {
    const isPimpinan = (row.jabatan || '').toLowerCase().includes('kepala') || (row.jabatan || '').toLowerCase().includes('wakil');
    const isCPG = (row.employeeStatus || '').toUpperCase() === 'CPG';
    if (isPimpinan) {
      ukkPerhari = 158250;
    } else if (isCPG) {
      ukkPerhari = 66125;
    } else {
      ukkPerhari = 132250;
    }
  }

  // 1. UKK Kotor / Bruto (Tersinkronisasi otomatis dengan Jumlah Hadir)
  // Tarif UKK harian efektif untuk kehadiran
  const effectiveDailyUkk = hariKerja > 0
    ? (baseUkkBruto / hariKerja)
    : (ukkPerhari > 0 ? (ukkPerhari * ((ukkKinerjaPersen || 100) / 100)) : 132250);

  let ukkKotor: number;
  if (options?.recalculateKotor && ukkPerhari > 0) {
    const baseDays = hariKerja > 0 ? hariKerja * 1.15 : 26;
    baseUkkBruto = Math.round(ukkPerhari * baseDays * ((ukkKinerjaPersen || 100) / 100));
    ukkKotor = hariKerja > 0 ? Math.round((baseUkkBruto / hariKerja) * jumlahHadir) : Math.round(effectiveDailyUkk * jumlahHadir);
  } else if (hariKerja > 0) {
    // Sinkronkan selalu proporsional dengan jumlah hadir terhadap hari kerja
    ukkKotor = Math.max(0, Math.round((baseUkkBruto / hariKerja) * jumlahHadir));
  } else {
    // Sinkronkan proporsional dengan jumlah hadir berdasarkan effective daily rate
    ukkKotor = Math.max(0, Math.round(effectiveDailyUkk * jumlahHadir));
  }

  const ukkBruto = ukkKotor;

  // 2. Perhitungan Akumulasi Poin / Hari Penalti Pemotongan UKK
  // - Terlambat < 5m = 0.5 hari UKK (50% UKK hari itu)
  // - Terlambat > 5m = 1.0 hari UKK (100% UKK hari itu hilang)
  // - Pulang cepat < 5m = 0.5 hari UKK (50% UKK hari itu)
  // - Pulang cepat > 5m = 1.0 hari UKK (100% UKK hari itu hilang)
  // - Kondite = 1.0 hari UKK
  const lateEarlyPoints = (datangLambatMin5 * 0.5) + (datangLambatPlus5 * 1.0) + (pulangCepatMin5 * 0.5) + (pulangCepatPlus5 * 1.0);
  const absencePoints = (sakit + izin + alpa + dinluar) * 1.0 + kondite;
  const totalPenaltyPoints = lateEarlyPoints + absencePoints;

  const potonganKeterlambatanRp = Math.round(lateEarlyPoints * ukkPerhari);
  // Jika ukkKotor sudah dipotong secara proporsional dari jumlahHadir,
  // jangan potong ganda absennya; hanya potong jika ukkKotor masih dihitung full
  const isBrutoAlreadyProrated = hariKerja > 0 && jumlahHadir < hariKerja;
  const potonganAbsenRp = isBrutoAlreadyProrated ? 0 : Math.round(absencePoints * ukkPerhari);

  let ukkPotongan = Number(row.ukkPotongan);
  if (options?.recalculatePotongan || isNaN(ukkPotongan) || row.ukkPotongan === undefined || options === undefined || isBrutoAlreadyProrated) {
    ukkPotongan = Math.min(ukkKotor, potonganKeterlambatanRp + potonganAbsenRp);
  }

  // Persentase Pemotongan
  const potonganTerlambatPersen = ukkKotor > 0
    ? Math.round((potonganKeterlambatanRp / ukkKotor) * 10000) / 100
    : 0;

  const potonganAbsenPersen = ukkKotor > 0
    ? Math.round((potonganAbsenRp / ukkKotor) * 10000) / 100
    : 0;

  const totalPotonganPersen = ukkKotor > 0
    ? Math.min(100, Math.round((ukkPotongan / ukkKotor) * 10000) / 100)
    : 0;

  // 3. UKK Bersih Diterima
  const ukkDiterima = Math.max(0, ukkKotor - ukkPotongan);

  // 4. Transpor
  const transporPerhari = Number(row.transporPerhari ?? row.tarifTransporHarian) || 0;
  const transporPotongan = Number(row.transporPotongan) || 0;
  const transporDiterima = Math.max(0, jumlahHadir * transporPerhari - transporPotongan);
  const transporBruto = jumlahHadir * transporPerhari;

  // 5. Uang Makan
  const uangMakanPerhari = Number(row.uangMakanPerhari ?? row.tarifUangMakanHarian) || 0;
  const uangMakanDiterima = Math.max(0, jumlahHadir * uangMakanPerhari);

  // 6. Grand Total (Akumulasi UKK Bersih + Transpor Bersih + Uang Makan Bersih)
  const totalJumlahUang = ukkDiterima + transporDiterima + uangMakanDiterima;
  const grandTotal = totalJumlahUang;

  return {
    id: row.id || `tu-${Date.now()}-${Math.random().toString(36).substr(2, 6)}`,
    no: Number(row.no) || 1,
    nip: row.nip || '',
    name: row.name || '',
    jabatan: row.jabatan || '',
    unitKerja: row.unitKerja || '',
    golongan: row.golongan || '',
    employeeStatus: row.employeeStatus || 'GTY',
    datangLambatMin5,
    datangLambatPlus5,
    terlambatMenit,
    potonganTerlambatPersen,
    pulangCepatMin5,
    pulangCepatPlus5,
    hariKerja,
    sakit,
    izin,
    alpa,
    cuti,
    dinluar,
    jumlahTidakMasuk,
    kondite,
    subuhOnline,
    potonganAbsenPersen,
    totalPotonganPersen,
    jumlahHadir,
    ukkPerhari,
    ukkKinerjaPersen,
    baseUkkBruto,
    ukkKotor,
    ukkBruto: ukkKotor,
    ukkPotongan,
    ukkDiterima,
    transporPerhari,
    tarifTransporHarian: transporPerhari,
    transporBruto,
    transporPotongan,
    transporDiterima,
    uangMakanPerhari,
    tarifUangMakanHarian: uangMakanPerhari,
    uangMakanDiterima,
    totalJumlahUang,
    grandTotal,
    period: row.period || '2026-08',
    periodLabel: row.periodLabel || 'Agustus 2026 (16 Juli 2026 - 13 Agustus 2026)',
    periodStartDate: row.periodStartDate || '2026-07-16',
    periodEndDate: row.periodEndDate || '2026-08-13',
    notes: row.notes || '',
    lastUpdated: row.lastUpdated || new Date().toISOString(),
  };
}

