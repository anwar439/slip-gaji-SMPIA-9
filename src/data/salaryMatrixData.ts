/**
 * Helper to auto-calculate all formula fields for a single matrix row
 * Cascades fully from Unit Value, Index Number, Performance %, Allowances, Regional, to Deductions & Net Paid
 */
export function calculateSalaryMatrixRow(data: Partial<SalaryCalculationSource>): SalaryCalculationSource {
  const indexNumber = Number(data.indexNumber) || 0;
  const performancePercent = data.performancePercent !== undefined ? Number(data.performancePercent) : 100;
  const indexValueNew = Number(data.indexValueNew) || 125000;
  const indexValueOld = Number(data.indexValueOld) || 123500;
  const indexDiff = indexValueNew - indexValueOld;

  // 1. Gaji Pokok Kinerja = (Angka Indeks * Nilai Indeks Satuan Baru) * (Prosen Kinerja / 100)
  const performanceBasicSalary = Math.round(indexNumber * indexValueNew * (performancePercent / 100));
  const positionAllowanceBasic = Number(data.positionAllowanceBasic !== undefined ? data.positionAllowanceBasic : (data.positionAllowance || 0));
  const totalSalaryAndAllowance = performanceBasicSalary + positionAllowanceBasic;

  // Base component for percentage allowances is the performanceBasicSalary
  const baseSalaryComponent = performanceBasicSalary;

  // 2. Tunjangan Pengabdian (Masa Kerja)
  // If dedicationAllowancePercent is explicitly set, use it; otherwise auto-infer from serviceYears if available
  const serviceYears = Number(data.serviceYears) || 0;
  const serviceMonths = Number(data.serviceMonths) || 0;
  let dedicationAllowancePercent = data.dedicationAllowancePercent !== undefined ? Number(data.dedicationAllowancePercent) : 0;
  if (data.dedicationAllowancePercent === undefined && serviceYears > 0) {
    if (serviceYears >= 20) dedicationAllowancePercent = 25;
    else if (serviceYears >= 15) dedicationAllowancePercent = 20;
    else if (serviceYears >= 10) dedicationAllowancePercent = 15;
    else if (serviceYears >= 5) dedicationAllowancePercent = 10;
    else dedicationAllowancePercent = 5;
  }
  const dedicationAllowanceAmount = Math.round(baseSalaryComponent * (dedicationAllowancePercent / 100));

  // 3. Tunjangan Keluarga (Istri: 10%, Anak: 5% per anak max 3)
  const husbandWifeCount = Number(data.husbandWifeCount) || 0;
  const childCount = Number(data.childCount) || 0;
  let familyAllowancePercent = data.familyAllowancePercent !== undefined ? Number(data.familyAllowancePercent) : 0;
  if (data.familyAllowancePercent === undefined || data.familyAllowancePercent === 0) {
    if (husbandWifeCount > 0 || childCount > 0) {
      familyAllowancePercent = (husbandWifeCount > 0 ? 10 : 0) + (Math.min(childCount, 3) * 5);
    }
  }
  const familyAllowanceAmount = Math.round(baseSalaryComponent * (familyAllowancePercent / 100));

  // 4. Tunjangan Yayasan / Peralihan
  const foundationAllowancePercent = Number(data.foundationAllowancePercent) || 0;
  const foundationAllowanceAmount = Math.round(baseSalaryComponent * (foundationAllowancePercent / 100));

  // 5. Tunjangan Jabatan Struktural
  const positionAllowance = positionAllowanceBasic;

  // 6. Gaji Kotor (Gross Salary) = Gaji Pokok + Total Tunjangan
  const totalAllowances = dedicationAllowanceAmount + familyAllowanceAmount + foundationAllowanceAmount + positionAllowance;
  const grossSalary = baseSalaryComponent + totalAllowances;

  // 7. Tunjangan Daerah (Default 10% dari Gaji Kotor)
  const regionalAllowancePercent = data.regionalAllowancePercent !== undefined ? Number(data.regionalAllowancePercent) : 10;
  const regionalAllowanceAmount = Math.round(grossSalary * (regionalAllowancePercent / 100));
  const otherAssistance = Number(data.otherAssistance) || 0;
  const totalSalaryReceived = grossSalary + regionalAllowanceAmount + otherAssistance;

  // 8. BPJS Kesehatan & Ketenagakerjaan
  const bpjsKesDeduction = data.bpjsKesDeduction !== undefined 
    ? Number(data.bpjsKesDeduction) 
    : (data.bpjsKesEmployee !== undefined ? Number(data.bpjsKesEmployee) : Math.round(performanceBasicSalary * 0.01));
  const bpjsKesEmployee = bpjsKesDeduction;
  const bpjsKesFoundation = data.bpjsKesFoundation !== undefined ? Number(data.bpjsKesFoundation) : Math.round(performanceBasicSalary * 0.04);
  const bpjsKesPremium = data.bpjsKesPremium !== undefined ? Number(data.bpjsKesPremium) : (bpjsKesEmployee + bpjsKesFoundation);

  const bpjsKtDeduction = data.bpjsKtDeduction !== undefined 
    ? Number(data.bpjsKtDeduction) 
    : (data.bpjsKtEmployee !== undefined ? Number(data.bpjsKtEmployee) : Math.round(performanceBasicSalary * 0.03));
  const bpjsKtEmployee = bpjsKtDeduction;
  const bpjsKtFoundation = data.bpjsKtFoundation !== undefined ? Number(data.bpjsKtFoundation) : Math.round(performanceBasicSalary * 0.0624);
  const bpjsKtPremium = data.bpjsKtPremium !== undefined ? Number(data.bpjsKtPremium) : (bpjsKtEmployee + bpjsKtFoundation);

  // 9. Potongan-Potongan Lainnya
  const infaqMasjid = Number(data.infaqMasjid) || 0;
  const coopLoanDeduction = Number(data.coopLoanDeduction) || 0;
  // Regional deduction by default offsets the regional allowance as per Al Azhar spreadsheet structure
  const regionalDeduction = data.regionalDeduction !== undefined ? Number(data.regionalDeduction) : regionalAllowanceAmount;
  const otherDeduction = Number(data.otherDeduction) || 0;

  // 10. Total Potongan & Gaji Dibayarkan (THP)
  const totalDeduction = bpjsKesDeduction + bpjsKtDeduction + infaqMasjid + coopLoanDeduction + regionalDeduction + otherDeduction;
  const netSalaryPaid = totalSalaryReceived - totalDeduction;

  return {
    id: data.id || `mat-${Date.now()}-${Math.random().toString(36).substr(2, 4)}`,
    no: data.no || 1,
    nip: data.nip || '',
    npwp: data.npwp || '',
    name: data.name || '',
    employeeStatus: data.employeeStatus || 'GTY',
    level: data.level || 'V D',
    category: data.category || 'GURU',
    indexNumber,
    performancePercent,
    percentBase: 100,
    indexValueOld,
    indexValueNew,
    indexDiff,
    performanceScorePercent: data.performanceScorePercent !== undefined ? Number(data.performanceScorePercent) : performancePercent,
    performanceBasicSalary,
    positionAllowanceBasic,
    totalSalaryAndAllowance,
    bpjsKesName: data.bpjsKesName || data.name || '',
    bpjsKesPremium,
    bpjsKesEmployee,
    bpjsKesFoundation,
    bpjsKtName: data.bpjsKtName || data.name || '',
    bpjsKtPremium,
    bpjsKtEmployee,
    bpjsKtFoundation,
    certificateNumber: data.certificateNumber || '',
    jhtPerYear: Number(data.jhtPerYear) || 0,
    jhtDeduction: Number(data.jhtDeduction) || 0,
    joinDateStr: data.joinDateStr || '',
    serviceYears,
    serviceMonths,
    gender: data.gender || 'L',
    taxStatus: data.taxStatus || 'TK/0',
    husbandWifeCount,
    childCount,
    baseSalaryComponent,
    dedicationAllowancePercent,
    dedicationAllowanceAmount,
    familyAllowancePercent,
    familyAllowanceAmount,
    foundationAllowancePercent,
    foundationAllowanceAmount,
    positionAllowance,
    totalAllowances,
    grossSalary,
    regionalAllowancePercent,
    regionalAllowanceAmount,
    otherAssistance,
    totalSalaryReceived,
    bpjsKesDeduction,
    bpjsKtDeduction,
    infaqMasjid,
    coopLoanDeduction,
    regionalDeduction,
    otherDeduction,
    totalDeduction,
    netSalaryPaid,
    notes: data.notes || '',
    lastUpdated: new Date().toISOString(),
  };
}
